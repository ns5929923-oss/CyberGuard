const navItems = [
  { to: '/admin/dashboard', label: 'Dashboard', Icon: DashboardIcon },
  { to: '/admin/users', label: 'Users', Icon: UsersIcon },
  { to: '/admin/scans', label: 'Scans', Icon: ScanIcon },
  { to: '/admin/findings', label: 'Findings', Icon: FindingIcon },
  { to: '/admin/settings', label: 'Settings', Icon: SettingsIcon },
]

export default function AdminSidebar({ mobileOpen, onClose }) {
  const { logout, user } = useAuth()
  const navigate = useNavigate()

  function handleLogout() {
    logout()
    navigate('/login')
  }

  const initials = user?.name
    ? user.name.split(' ').map(w => w[0]).slice(0, 2).join('').toUpperCase()
    : 'A'

  const linkClass = ({ isActive }) =>
    [
      'flex items-center gap-3 px-3 py-2.5 rounded-lg text-sm font-medium transition-all duration-150',
      isActive
        ? 'bg-purple-600/20 text-purple-400 border border-purple-500/30'
        : 'text-slate-400 hover:text-slate-200 hover:bg-white/5 border border-transparent',
    ].join(' ')

  const sidebarContent = (
    <div className="flex flex-col h-full">
      {/* Logo */}
      <div className="flex items-center gap-3 px-4 py-5 border-b border-[var(--border-color)]">
        <div className="flex items-center justify-center w-8 h-8 rounded-lg bg-purple-600/20 border border-purple-500/30 text-purple-400 flex-shrink-0">
          <ShieldIcon />
        </div>
        <div className="min-w-0">
          <span className="text-slate-100 font-semibold tracking-tight text-sm">CyberGuard</span>
          <p className="text-[10px] text-purple-400 -mt-0.5 font-semibold uppercase tracking-widest">Admin Panel</p>
        </div>
      </div>

      {/* Section label */}
      <div className="px-4 pt-4 pb-1">
        <p className="text-[10px] font-semibold text-slate-600 uppercase tracking-widest">Administration</p>
      </div>

      {/* Nav */}
      <nav className="flex-1 px-3 space-y-0.5 overflow-y-auto">
        {navItems.map(({ to, label, Icon }) => (
          <NavLink key={to} to={to} end={to === '/admin/dashboard'} className={linkClass} onClick={onClose}>
            <Icon />
            {label}
          </NavLink>
        ))}
      </nav>

      {/* Admin badge + Logout */}
      <div className="p-3 border-t border-[var(--border-color)] space-y-1">
        <div className="flex items-center gap-3 px-3 py-2 rounded-lg bg-white/[0.02] border border-purple-500/20">
          <div className="flex items-center justify-center w-7 h-7 rounded-full bg-purple-600/20 border border-purple-500/30 text-purple-400 text-xs font-semibold flex-shrink-0">
            {initials}
          </div>
          <div className="flex-1 min-w-0">
            <p className="text-xs font-medium text-slate-300 truncate leading-tight">{user?.name}</p>
            <p className="text-[10px] text-purple-400 truncate leading-tight font-semibold uppercase tracking-wider">Administrator</p>
          </div>
        </div>
        <button
          onClick={handleLogout}
          className="flex items-center gap-3 w-full px-3 py-2 rounded-lg text-sm font-medium text-slate-400 hover:text-red-400 hover:bg-red-500/10 transition-all duration-150 border border-transparent hover:border-red-500/20"
        >
          <LogoutIcon />
          Sign out
        </button>
      </div>
    </div>
  )

  return (
    <>
      {/* Desktop sidebar */}
      <aside className="hidden lg:flex flex-col w-56 shrink-0 h-screen sticky top-0 bg-[var(--bg-secondary)] border-r border-[var(--border-color)]">
        {sidebarContent}
      </aside>

      {/* Mobile overlay */}
      {mobileOpen && (
        <div className="lg:hidden fixed inset-0 z-40 flex">
          <div className="fixed inset-0 bg-black/60 backdrop-blur-sm" onClick={onClose} />
          <aside className="relative z-50 flex flex-col w-64 h-full bg-[var(--bg-secondary)] border-r border-[var(--border-color)]">
            {sidebarContent}
          </aside>
        </div>
      )}
    </>
  )
}
